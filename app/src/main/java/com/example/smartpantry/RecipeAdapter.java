package com.example.smartpantry;

import android.content.Context;
import android.view.LayoutInflater;
import android.view.View;
import android.view.ViewGroup;
import android.widget.BaseAdapter;
import android.widget.TextView;

import java.util.List;

public class RecipeAdapter extends BaseAdapter {
    private final Context context;
    private final List<Recipe> recipes;

    public RecipeAdapter(Context context, List<Recipe> recipes) {
        this.context = context;
        this.recipes = recipes;
    }

    @Override
    public int getCount() {
        return recipes.size();
    }

    @Override
    public Recipe getItem(int position) {
        return recipes.get(position);
    }

    @Override
    public long getItemId(int position) {
        return getItem(position).id;
    }

    @Override
    public View getView(int position, View convertView, ViewGroup parent) {
        View view = convertView;
        if (view == null) {
            view = LayoutInflater.from(context).inflate(R.layout.row_recipe, parent, false);
        }
        Recipe recipe = getItem(position);
        TextView title = view.findViewById(R.id.recipeTitle);
        TextView subtitle = view.findViewById(R.id.recipeSubtitle);
        title.setText(recipe.name);
        subtitle.setText(recipe.ingredients.size() + " matched ingredients");
        return view;
    }
}
